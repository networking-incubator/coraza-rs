//! Generates Rust tables from the crate's canonical SQL and XSS data.

use std::{env, fmt::Write as _, fs, io, path::Path};

/// Upstream-generated `KEY<TAB>BYTE` rows, sorted by key.
const DATA: &str = "data/sqli_keywords.txt";
/// Local `KEY<TAB>BYTE` additions merged into [`DATA`].
const LOCAL_DATA: &str = "data/sqli_keywords_local.txt";
/// Upstream-generated XSS event, attribute, and tag rows.
const XSS_DATA: &str = "data/xss_tables.txt";
/// Local XSS additions merged into [`XSS_DATA`].
const LOCAL_XSS_DATA: &str = "data/xss_tables_local.txt";

/// The generated table name for a keyword type byte.
fn token_type(byte: &str) -> Option<&'static str> {
    Some(match byte {
        "k" => "Keyword",
        "U" => "Union",
        "B" => "Group",
        "E" => "Expression",
        "t" => "SqlType",
        "f" => "Function",
        "n" => "Bareword",
        "1" => "Number",
        "v" => "Variable",
        "s" => "String",
        "o" => "Operator",
        "&" => "LogicOperator",
        "c" => "Comment",
        "A" => "Collate",
        "T" => "Tsql",
        "F" => "Fingerprint",
        _ => return None,
    })
}

/// Fails when `names` repeats a value, naming the first repeat.
fn reject_duplicates<'a>(kind: &str, names: impl Iterator<Item = &'a str>) -> Result<(), Box<dyn std::error::Error>> {
    let mut seen = std::collections::HashSet::new();
    for name in names {
        if !seen.insert(name) {
            return Err(io::Error::new(io::ErrorKind::InvalidData, format!("duplicate {kind} {name:?}")).into());
        }
    }
    Ok(())
}

/// A parsed SQL row: the key and its generated token type name.
type SqlRow<'a> = (&'a str, &'static str);

/// Parses `KEY<TAB>BYTE` rows, rejecting malformed, unknown, or non-ASCII ones.
fn sql_rows(text: &str) -> Result<Vec<SqlRow<'_>>, Box<dyn std::error::Error>> {
    let mut rows = Vec::new();
    for line in text.lines().filter(|line| !line.is_empty() && !line.starts_with('#')) {
        let (key, byte) = line
            .split_once('\t')
            .ok_or_else(|| io::Error::new(io::ErrorKind::InvalidData, format!("no tab in row {line:?}")))?;
        let kind = token_type(byte)
            .ok_or_else(|| io::Error::new(io::ErrorKind::InvalidData, format!("unknown keyword type {byte:?}")))?;
        if !key.is_ascii() {
            return Err(io::Error::new(io::ErrorKind::InvalidData, format!("non-ASCII key {key:?}")).into());
        }
        rows.push((key, kind));
    }
    Ok(rows)
}

/// Generates XSS tables and rejects malformed, duplicate, or incomplete rows.
///
/// `texts` holds the upstream-generated rows first and the local additions
/// after them, so each kind keeps the upstream entries ahead of the local
/// ones.
fn xss_tables(texts: &[&str]) -> Result<String, Box<dyn std::error::Error>> {
    let mut events = Vec::new();
    let mut attrs = Vec::new();
    let mut tags = Vec::new();
    for line in texts
        .iter()
        .flat_map(|text| text.lines())
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
    {
        match line.split('\t').collect::<Vec<_>>().as_slice() {
            ["event", name] => events.push(*name),
            ["tag", name] => tags.push(*name),
            ["attr", name, kind] => attrs.push((*name, *kind)),
            _ => {
                return Err(
                    io::Error::new(io::ErrorKind::InvalidData, format!("invalid XSS table row {line:?}")).into(),
                );
            },
        }
    }
    if events.is_empty() || attrs.is_empty() || tags.is_empty() {
        return Err(io::Error::new(io::ErrorKind::InvalidData, "incomplete XSS tables").into());
    }
    reject_duplicates("XSS event", events.iter().copied())?;
    reject_duplicates("XSS tag", tags.iter().copied())?;
    reject_duplicates("XSS attribute", attrs.iter().map(|&(name, _)| name))?;

    let mut out = String::from(
        "// @generated by build.rs from data/xss_tables.txt and data/xss_tables_local.txt.\n\n\
         use super::Attribute as A;\n\n\
         #[rustfmt::skip]\n\
         /// XSS event attribute names from the pinned upstream table and the local additions.\n",
    );
    writeln!(&mut out, "pub static BLACK_ATTR_EVENTS: [&str; {}] = [", events.len())?;
    for event in events {
        if !event.is_ascii() {
            return Err(io::Error::new(io::ErrorKind::InvalidData, format!("non-ASCII event {event:?}")).into());
        }
        writeln!(&mut out, "    {event:?},")?;
    }
    out.push_str("];\n\n#[rustfmt::skip]\n/// XSS attribute names and their matching policies.\n");
    writeln!(&mut out, "pub static BLACK_ATTRS: [(&str, A); {}] = [", attrs.len())?;
    for (name, kind) in attrs {
        let kind = match kind {
            "Black" => "Black",
            "Url" => "Url",
            "Style" => "Style",
            "Indirect" => "Indirect",
            _ => {
                return Err(io::Error::new(
                    io::ErrorKind::InvalidData,
                    format!("unknown XSS attribute type {kind:?}"),
                )
                .into());
            },
        };
        if !name.is_ascii() {
            return Err(io::Error::new(io::ErrorKind::InvalidData, format!("non-ASCII attribute {name:?}")).into());
        }
        writeln!(&mut out, "    ({name:?}, A::{kind}),")?;
    }
    out.push_str("];\n\n#[rustfmt::skip]\n/// XSS tag names from the pinned upstream table and the local additions.\n");
    writeln!(&mut out, "pub static BLACK_TAGS: [&str; {}] = [", tags.len())?;
    for tag in tags {
        if !tag.is_ascii() {
            return Err(io::Error::new(io::ErrorKind::InvalidData, format!("non-ASCII tag {tag:?}")).into());
        }
        writeln!(&mut out, "    {tag:?},")?;
    }
    out.push_str("];\n");
    Ok(out)
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let manifest = Path::new(env!("CARGO_MANIFEST_DIR"));
    let data = manifest.join(DATA);
    let local_data = manifest.join(LOCAL_DATA);
    let xss_data = manifest.join(XSS_DATA);
    let local_xss_data = manifest.join(LOCAL_XSS_DATA);
    for path in [&data, &local_data, &xss_data, &local_xss_data] {
        println!("cargo:rerun-if-changed={}", path.display());
    }
    let text = fs::read_to_string(&data)?;
    let local_text = fs::read_to_string(&local_data)?;

    // Both tables are sorted, so merging them keeps the lookup order the
    // binary search and the generated hash table rely on.
    let mut rows = sql_rows(&text)?;
    rows.extend(sql_rows(&local_text)?);
    rows.sort_by_key(|&(key, _)| key);
    let sorted = rows
        .windows(2)
        .all(|pair| pair.first().zip(pair.get(1)).is_some_and(|(a, b)| a.0 < b.0));
    if !sorted {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            format!("{} and {} have duplicate keys", data.display(), local_data.display()),
        )
        .into());
    }

    let mut out = format!(
        "// @generated by build.rs from {DATA} and {LOCAL_DATA}.\n\n\
         use super::token::TokenType as T;\n\n\
         #[rustfmt::skip]\n\
         /// SQL words, operators, and fingerprints in lookup order.\n\
         pub static SQL_KEYWORDS: [(&str, T); {}] = [\n",
        rows.len()
    );
    for (key, kind) in rows {
        writeln!(&mut out, "    ({key:?}, T::{kind}),")?;
    }
    out.push_str("];\n");

    let output_dir =
        env::var_os("OUT_DIR").ok_or_else(|| io::Error::new(io::ErrorKind::NotFound, "OUT_DIR is not set"))?;
    let output_dir = Path::new(&output_dir);
    fs::write(output_dir.join("keyword_table.rs"), out)?;
    let xss_text = fs::read_to_string(&xss_data)?;
    let local_xss_text = fs::read_to_string(&local_xss_data)?;
    fs::write(
        output_dir.join("xss_tables.rs"),
        xss_tables(&[&xss_text, &local_xss_text])?,
    )?;
    Ok(())
}
