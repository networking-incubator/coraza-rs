//! The best-fit Unicode-to-ASCII mapping `t:urlDecodeUni` folds `%uHHHH` escapes with.

/// The ASCII byte ModSecurity's best-fit mapping for code page 20127 (US-ASCII) folds
/// `code` to, such as `"` for U+201C; `None` for a code point it doesn't map.
///
/// This is the table ModSecurity's `unicode.mapping` holds for that code page, which
/// CRS's reference containers load (`SecUnicodeMapFile`), as Go Coraza has it. It folds
/// typographic punctuation and full-width ASCII; it isn't a defence against lookalike
/// characters from other scripts.
pub(super) fn best_fit_ascii(code: u16) -> Option<u8> {
    BEST_FIT_ASCII
        .binary_search_by_key(&code, |&(mapped, _)| mapped)
        .ok()
        .and_then(|index| BEST_FIT_ASCII.get(index).map(|entry| entry.1))
}

