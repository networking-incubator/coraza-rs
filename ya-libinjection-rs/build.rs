//! Generates Rust tables from the crate's canonical SQL and XSS data.

use std::{env, fs, path::Path};

/// Canonical `KEY<TAB>BYTE` rows, sorted by key.
const DATA: &str = "data/sqli_keywords.txt";
const XSS_DATA: &str = "data/xss_tables.txt";

/// The `TokenType` a table value stands for.
fn token_type(byte: &str) -> &'static str {
    match byte {
        "k" => "Keyword",
        "U" => "Union",
        "B" => "Group",
        "E" => "Expression",
        "t" => "SqlType",
        "f" => "Function",
        "n" => "Bareword",
        "1" => "Number",
        "v" => "Variable",
        "s" => "String",
        "o" => "Operator",
        "&" => "LogicOperator",
        "c" => "Comment",
        "A" => "Collate",
        "T" => "Tsql",
        "F" => "Fingerprint",
        _ => panic!("unknown keyword type {byte:?}"),
    }
}

fn xss_tables(text: &str) -> String {
    let mut events = Vec::new();
    let mut attrs = Vec::new();
    let mut tags = Vec::new();
    for line in text
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
    {
        let fields: Vec<_> = line.split('\t').collect();
        match fields.as_slice() {
            ["event", name] => events.push(*name),
            ["tag", name] => tags.push(*name),
            ["attr", name, kind] => attrs.push((*name, *kind)),
            _ => panic!("invalid XSS table row {line:?}"),
        }
    }
    assert!(
        !events.is_empty() && !attrs.is_empty() && !tags.is_empty(),
        "incomplete XSS tables"
    );

    let mut out = String::from(
        "// @generated by build.rs from data/xss_tables.txt.\n\n\
         use super::Attribute as A;\n\n\
         #[rustfmt::skip]\n",
    );
    out.push_str(&format!("pub static BLACK_ATTR_EVENTS: [&str; {}] = [\n", events.len()));
    for event in events {
        assert!(event.is_ascii(), "non-ASCII event {event:?}");
        out.push_str(&format!("    {event:?},\n"));
    }
    out.push_str("];\n\n#[rustfmt::skip]\n");
    out.push_str(&format!("pub static BLACK_ATTRS: [(&str, A); {}] = [\n", attrs.len()));
    for (name, kind) in attrs {
        let kind = match kind {
            "Black" => "Black",
            "Url" => "Url",
            "Style" => "Style",
            "Indirect" => "Indirect",
            _ => panic!("unknown XSS attribute type {kind:?}"),
        };
        assert!(name.is_ascii(), "non-ASCII attribute {name:?}");
        out.push_str(&format!("    ({name:?}, A::{kind}),\n"));
    }
    out.push_str("];\n\n#[rustfmt::skip]\n");
    out.push_str(&format!("pub static BLACK_TAGS: [&str; {}] = [\n", tags.len()));
    for tag in tags {
        assert!(tag.is_ascii(), "non-ASCII tag {tag:?}");
        out.push_str(&format!("    {tag:?},\n"));
    }
    out.push_str("];\n");
    out
}

fn main() {
    let manifest = Path::new(env!("CARGO_MANIFEST_DIR"));
    let data = manifest.join(DATA);
    let xss_data = manifest.join(XSS_DATA);
    println!("cargo:rerun-if-changed={}", data.display());
    println!("cargo:rerun-if-changed={}", xss_data.display());
    let text = fs::read_to_string(&data).unwrap_or_else(|e| panic!("{}: {e}", data.display()));

    let rows: Vec<(&str, &str)> = text
        .lines()
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .map(|line| {
            line.split_once('\t')
                .unwrap_or_else(|| panic!("no tab in row {line:?}"))
        })
        .collect();
    // `lookup_word`'s tests, like upstream's lookup, rely on the order.
    assert!(
        rows.windows(2).all(|pair| pair[0].0 < pair[1].0),
        "{} is not sorted, or holds a duplicate",
        data.display()
    );

    let mut out = format!(
        "// @generated by build.rs from {DATA}.\n\n\
         use super::token::TokenType as T;\n\n\
         #[rustfmt::skip]\n\
         pub static SQL_KEYWORDS: [(&str, T); {}] = [\n",
        rows.len()
    );
    for (key, byte) in rows {
        // `{key:?}` escapes the quotes and backslashes of the printable ASCII keys.
        assert!(key.is_ascii(), "non-ASCII key {key:?}");
        out.push_str(&format!("    ({key:?}, T::{}),\n", token_type(byte)));
    }
    out.push_str("];\n");

    let dest = Path::new(&env::var_os("OUT_DIR").expect("OUT_DIR")).join("keyword_table.rs");
    fs::write(dest, out).expect("write keyword_table.rs");

    let xss_text = fs::read_to_string(&xss_data).unwrap_or_else(|e| panic!("{}: {e}", xss_data.display()));
    let xss_dest = Path::new(&env::var_os("OUT_DIR").expect("OUT_DIR")).join("xss_tables.rs");
    fs::write(xss_dest, xss_tables(&xss_text)).expect("write xss_tables.rs");
}
